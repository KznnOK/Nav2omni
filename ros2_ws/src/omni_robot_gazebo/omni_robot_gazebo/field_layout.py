"""Field geometry from field_layout.yaml.

One definition feeds the Gazebo model (SDF), the Nav2 map (PNG + YAML) and
any geometric check (LiDAR visibility, collision). Rectangles are returned in
world meters as (name, x0, x1, y0, y1) for the whole field: the red court from
the file plus its mirror image for the blue court.
"""
import argparse
import os

import yaml


def default_layout_file():
    from ament_index_python.packages import get_package_share_directory
    return os.path.join(
        get_package_share_directory("omni_robot_gazebo"),
        "config", "field_layout.yaml")


def load_layout(path=None):
    with open(path or default_layout_file()) as stream:
        return yaml.safe_load(stream)


def _to_world(layout, rect):
    half = 0.5 * layout["field_size"]
    x0, x1, y0, y1 = rect
    return ((x0 - half) / 1000.0, (x1 - half) / 1000.0,
            (y0 - half) / 1000.0, (y1 - half) / 1000.0)


def _mirror(layout, rect):
    size = layout["field_size"]
    x0, x1, y0, y1 = rect
    return [size - x1, size - x0, y0, y1]


def _red_frames(layout):
    frames = []
    for name, rect in layout["frames"].items():
        if name == "rungs":
            continue
        frames.append((name, rect))
    rungs = layout["frames"]["rungs"]
    width = layout["frame"]["width"]
    for index, top in enumerate(rungs["y_top"]):
        frames.append((f"rung_{index + 1}",
                       [rungs["x"][0], rungs["x"][1], top - width, top]))
    return frames


def frame_rects(layout, red_only=False):
    """Wood frames (38 x 89 mm) in world meters."""
    rects = []
    for name, rect in _red_frames(layout):
        rects.append((f"red_{name}",) + _to_world(layout, rect))
        if not red_only:
            rects.append((f"blue_{name}",)
                         + _to_world(layout, _mirror(layout, rect)))
    return rects


def line_rects(layout):
    """Visual-only floor markings as (name, x0, x1, y0, y1, color)."""
    colors = layout["colors"]
    items = []
    for name, rect in layout["lines"].items():
        items.append((name, rect, colors["line"], colors["line"]))
    items.append(("start_tape", layout["start_tape"],
                  colors["red_tape"], colors["blue_tape"]))
    marker = layout["dice_marker"]
    x0, x1, y0, y1 = marker["outer"]
    w = marker["line_width"]
    for suffix, rect in (("l", [x0, x0 + w, y0, y1]), ("r", [x1 - w, x1, y0, y1]),
                         ("b", [x0, x1, y0, y0 + w]), ("t", [x0, x1, y1 - w, y1])):
        items.append((f"dice_marker_{suffix}", rect,
                      colors["line"], colors["line"]))
    result = []
    for name, rect, red_color, blue_color in items:
        result.append((f"red_{name}",) + _to_world(layout, rect) + (red_color,))
        result.append((f"blue_{name}",)
                      + _to_world(layout, _mirror(layout, rect)) + (blue_color,))
    return result


def zone_world(layout, name):
    return _to_world(layout, layout["zones"][name])


def _box(name, x0, x1, y0, y1, z0, z1, color, collision):
    cx, cy, cz = 0.5 * (x0 + x1), 0.5 * (y0 + y1), 0.5 * (z0 + z1)
    size = f"{x1 - x0:.4f} {y1 - y0:.4f} {z1 - z0:.4f}"
    pose = f"{cx:.4f} {cy:.4f} {cz:.4f} 0 0 0"
    rgba = f"{color[0]} {color[1]} {color[2]} 1"
    text = ""
    if collision:
        text += (f"      <collision name=\"{name}_collision\">\n"
                 f"        <pose>{pose}</pose>\n"
                 f"        <geometry><box><size>{size}</size></box></geometry>\n"
                 f"      </collision>\n")
    text += (f"      <visual name=\"{name}_visual\">\n"
             f"        <pose>{pose}</pose>\n"
             f"        <geometry><box><size>{size}</size></box></geometry>\n"
             f"        <material><ambient>{rgba}</ambient>"
             f"<diffuse>{rgba}</diffuse></material>\n"
             f"      </visual>\n")
    return text


def write_sdf(layout, path, model_name="kansai_field_2027"):
    height = layout["frame"]["height"] / 1000.0
    half = 0.5 * layout["field_size"] / 1000.0
    colors = layout["colors"]
    body = _box("floor", -half, half, -half, half, 0.0, 0.0005,
                colors["floor"], collision=False)
    for name, x0, x1, y0, y1, color in line_rects(layout):
        body += _box(name, x0, x1, y0, y1, 0.0005, 0.0008, color,
                     collision=False)
    for name, x0, x1, y0, y1 in frame_rects(layout):
        body += _box(name, x0, x1, y0, y1, 0.0, height, colors["frame"],
                     collision=True)
    sdf = ("<?xml version=\"1.0\"?>\n"
           "<!-- Generated by omni_robot_gazebo/field_layout.py from "
           "config/field_layout.yaml. Do not edit by hand. -->\n"
           "<sdf version=\"1.7\">\n"
           f"  <model name=\"{model_name}\">\n"
           "    <static>true</static>\n"
           "    <link name=\"field_link\">\n"
           f"{body}"
           "    </link>\n"
           "  </model>\n"
           "</sdf>\n")
    with open(path, "w") as stream:
        stream.write(sdf)


def write_map(layout, png_path, yaml_path, resolution=0.01):
    import numpy as np
    from PIL import Image

    half = 0.5 * layout["field_size"] / 1000.0
    cells = int(round(2 * half / resolution))
    image = np.full((cells, cells), 254, dtype=np.uint8)
    for _, x0, x1, y0, y1 in frame_rects(layout):
        c0 = int(np.floor((x0 + half) / resolution + 1e-6))
        c1 = int(np.ceil((x1 + half) / resolution - 1e-6))
        r0 = int(np.floor((y0 + half) / resolution + 1e-6))
        r1 = int(np.ceil((y1 + half) / resolution - 1e-6))
        # image rows grow downward from the top edge (y = +half)
        image[cells - r1:cells - r0, c0:c1] = 0
    Image.fromarray(image).save(png_path)
    with open(yaml_path, "w") as stream:
        stream.write(
            "# Generated by omni_robot_gazebo/field_layout.py from "
            "config/field_layout.yaml.\n"
            f"image: {os.path.basename(png_path)}\n"
            "mode: trinary\n"
            f"resolution: {resolution}\n"
            f"origin: [{-half}, {-half}, 0.0]\n"
            "negate: 0\n"
            "occupied_thresh: 0.65\n"
            "free_thresh: 0.25\n")


def main():
    parser = argparse.ArgumentParser(
        description="Generate the field SDF and Nav2 map from field_layout.yaml")
    parser.add_argument("--layout", default=None)
    parser.add_argument("--sdf", required=True)
    parser.add_argument("--map-png", required=True)
    parser.add_argument("--map-yaml", required=True)
    args = parser.parse_args()
    layout = load_layout(args.layout)
    write_sdf(layout, args.sdf)
    write_map(layout, args.map_png, args.map_yaml)
    print(f"wrote {args.sdf}, {args.map_png}, {args.map_yaml}")


if __name__ == "__main__":
    main()
